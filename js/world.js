const ROOM_BY_ID = {};
for (const d of ROOM_DEFS) ROOM_BY_ID[d.id] = d;

// ------------------------------------------------------------
//  房间实例
// ------------------------------------------------------------
class Room {
  constructor(def) {
    this.def = def; this.id = def.id; this.name = def.name; this.area = def.area;
    this.A = AREAS[def.area];
    this.gx = def.x; this.gy = def.y;
    const rows = def.map;
    this.h = rows.length; this.w = 0;
    for (const r of rows) this.w = Math.max(this.w, r.length);
    this.tiles = new Uint8Array(this.w * this.h);
    this.spawns = [];
    for (let y = 0; y < this.h; y++) {
      for (let x = 0; x < this.w; x++) {
        const ch = rows[y][x] || '#';
        let t = T_EMPTY;
        switch (ch) {
          case '#': t = T_SOLID; break;
          case '^': t = T_SPIKE; break;
          case '=': t = T_ONEWAY; break;
          case 'X': t = T_BREAK; break;
          case 'D': t = T_GATE; break;
          case '~': t = T_SPIKE; break;
          case 'O': t = T_SEAL; break;
          case 'G': t = T_LGATE; break;
          case '.': case ' ': break;
          default: this.spawns.push({ ch, tx: x, ty: y });
        }
        this.tiles[y * this.w + x] = t;
      }
    }
    this.pw = this.w * TILE; this.ph = this.h * TILE;
    this.gateClosed = false;
    this.breakHits = {};
  }
  tileRaw(tx, ty) {
    if (tx < 0 || ty < 0 || tx >= this.w || ty >= this.h) return -1;
    return this.tiles[ty * this.w + tx];
  }
  // 越界时延伸边缘瓦片：边缘开口即为通道，边缘墙即为封闭
  tile(tx, ty) {
    tx = tx < 0 ? 0 : tx >= this.w ? this.w - 1 : tx;
    ty = ty < 0 ? 0 : ty >= this.h ? this.h - 1 : ty;
    return this.tiles[ty * this.w + tx];
  }
  setTile(tx, ty, v) { if (tx >= 0 && ty >= 0 && tx < this.w && ty < this.h) this.tiles[ty * this.w + tx] = v; }
  isSolid(tx, ty) { const t = this.tile(tx, ty); return t === T_SOLID || t === T_BREAK || t === T_SEAL || t === T_LGATE || (t === T_GATE && this.gateClosed); }
  // 可破坏墙：洪泛找连通组
  breakGroup(tx, ty, type = T_BREAK) {
    const out = [], seen = new Set(), st = [[tx, ty]];
    while (st.length) {
      const [x, y] = st.pop(); const k = x + ',' + y;
      if (seen.has(k) || this.tileRaw(x, y) !== type) continue;
      seen.add(k); out.push([x, y]);
      st.push([x + 1, y], [x - 1, y], [x, y + 1], [x, y - 1]);
    }
    return out;
  }
}

// 根据全局像素坐标查找房间
function roomAtGlobal(px, py) {
  const tx = Math.floor(px / TILE), ty = Math.floor(py / TILE);
  for (const d of ROOM_DEFS) {
    const w = d.map[0].length, h = d.map.length;
    if (tx >= d.x && tx < d.x + w && ty >= d.y && ty < d.y + h) return d;
  }
  return null;
}
